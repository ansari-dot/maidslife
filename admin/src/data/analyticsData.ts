// Calculate totals and metrics helper
export const getAnalyticsSummary = (data: DailyAnalyticsPoint[]) => {
  const totalRevenue = data.reduce((acc, d) => acc + d.totalRevenue, 0);
  const totalBookings = data.reduce((acc, d) => acc + d.totalBookings, 0);
  const avgOrderValue = totalBookings > 0 ? Math.round(totalRevenue / totalBookings) : 0;
  const avgDailyRevenue = data.length > 0 ? Math.round(totalRevenue / data.length) : 0;
  const avgDailyBookings = data.length > 0 ? Number((totalBookings / data.length).toFixed(1)) : 0;

  // Best day
  let bestDay = data[0];
  for (const day of data) {
    if (day.totalRevenue > (bestDay?.totalRevenue || 0)) {
      bestDay = day;
    }
  }

  // Category shares
  const residentialRev = data.reduce((acc, d) => acc + d.residentialRevenue, 0);
  const deepCleaningRev = data.reduce((acc, d) => acc + d.deepCleaningRevenue, 0);
  const moveInOutRev = data.reduce((acc, d) => acc + d.moveInOutRevenue, 0);
  const otherRev = data.reduce((acc, d) => acc + d.otherRevenue, 0);

  return {
    totalRevenue,
    totalBookings,
    avgOrderValue,
    avgDailyRevenue,
    avgDailyBookings,
    bestDay,
    categoryShare: {
      residential: Math.round((residentialRev / totalRevenue) * 100),
      deepCleaning: Math.round((deepCleaningRev / totalRevenue) * 100),
      moveInOut: Math.round((moveInOutRev / totalRevenue) * 100),
      other: Math.round((otherRev / totalRevenue) * 100),
    },
  };
};
